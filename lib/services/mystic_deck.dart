  /// Calculate biorhythm value for a given day
  static double biorhythm(DateTime birth, DateTime target, String type) {
    final days = target.difference(birth).inDays;
    final period = switch (type) {
      '신체' => 23, '감정' => 28, '지성' => 33, _ => 23,
    };
    return sin(2 * pi * days / period);
  }

  /// Get today's biorhythm status
  Map<String, String> todaysBiorhythm(DateTime birth) {
    final now = DateTime.now();
    return {
      '신체': _rhythmText(biorhythm(birth, now, '신체')),
      '감정': _rhythmText(biorhythm(birth, now, '감정')),
      '지성': _rhythmText(biorhythm(birth, now, '지성')),
    };
  }

  String _rhythmText(double v) {
    if (v > 0.7) return '최고조 🔥';
    if (v > 0.3) return '상승 📈';
    if (v > -0.3) return '보통 😐';
    if (v > -0.7) return '하락 📉';
    return '주의 ⚠️';
  }

